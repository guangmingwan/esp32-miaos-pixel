extern "C" __attribute__((weak)) void esp32_task_wdt_reset(void) {
  static int64_t last_us = 0;
  const int64_t now_us = esp_timer_get_time();
  if (now_us - last_us >= 500000) {
    delay(1);
    last_us = now_us;
  }
}

